export function stateSections(teaching: TeachingState, snapshot: string, history = ""): Record<string, string> {
  return {
    "<lesson>": `课题：${teaching.title || "（等待学习者给出）"}`,
    "<progress>": `已讲通：${teaching.concepts.join("、") || "无"}\n学习者状态：${teaching.learner || "尚无观察"}\n已完成旁拍：${teaching.beatsDone}`,
    ...(history ? { "<learner-history>": history } : {}),
    "<stage>": snapshot,
  };
}

